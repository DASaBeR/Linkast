using Linkast.Core;
using Linkast.Core.Audio;

namespace Linkast.Engine.FFmpeg;

/// <summary>An audio input as FFmpeg will see it.</summary>
public abstract record AudioJobInput(double Gain)
{
    /// <summary>
    /// Filter name suffix, for example "mic" gives <c>volume@mic</c>. Named inputs can be changed live
    /// through the command channel; unnamed inputs get plain filters.
    /// </summary>
    public string? Name { get; init; }

    /// <summary>
    /// Null: no noise filter. True or false: an <c>afftdn@{Name}</c> filter is included, switched on or
    /// (nearly) off, so it can be toggled live without restarting.
    /// </summary>
    public bool? NoiseSuppression { get; init; }
}

/// <summary>Raw PCM delivered by Linkast over a named pipe.</summary>
public sealed record PipeAudioJobInput(string PipePath, PcmFormat Format, double Gain) : AudioJobInput(Gain);

/// <summary>A sine tone generated by FFmpeg itself (tests and test streams).</summary>
public sealed record ToneAudioJobInput(double Gain) : AudioJobInput(Gain);

/// <summary>Where a layer's picture comes from.</summary>
public enum LayerInputKind
{
    /// <summary>Raw BGRA frames from Linkast over a named pipe (cameras, overlays).</summary>
    Pipe,

    /// <summary>A video file FFmpeg decodes, loops for ever and paces to real time (a scene's video).</summary>
    LoopingVideo,

    /// <summary>A picture file read once; the overlay keeps showing it (a scene's picture or card).</summary>
    Still,
}

/// <summary>A layer overlaid at <paramref name="Placement"/>: a rendered pipe, or a file FFmpeg reads itself.</summary>
public sealed record VideoLayerJobInput(string PipePath, int Width, int Height, int FrameRate, Linkast.Core.Camera.PixelRect Placement)
{
    public LayerInputKind Kind { get; init; } = LayerInputKind.Pipe;

    /// <summary>The picture or video for <see cref="LayerInputKind.LoopingVideo"/> and <see cref="LayerInputKind.Still"/>.</summary>
    public string? FilePath { get; init; }

    /// <summary>
    /// Fills the canvas, cropping what overflows, at a fixed size (scene media). Such a layer is only
    /// shown and hidden live, never resized.
    /// </summary>
    public bool Cover { get; init; }

    /// <summary>For a video with sound: the channel its sound is mixed as (<c>volume@{name}</c>), and the starting gain.</summary>
    public string? AudioName { get; init; }

    public double AudioGain { get; init; } = 1;
}

/// <summary>Fully resolved input to <see cref="FfmpegArgumentBuilder"/>.</summary>
/// <param name="PublishUrl">Complete RTMP URL including the stream key, or null to only record. Treated as a secret.</param>
/// <param name="TcUrl">tcUrl to announce, or null to let FFmpeg derive it from <paramref name="PublishUrl"/>.</param>
public sealed record FfmpegJob(
    VideoSourceSpec Video,
    IReadOnlyList<AudioJobInput> Audio,
    EncoderSettings Encoder,
    string? PublishUrl,
    string? TcUrl)
{
    /// <summary>A local .mkv file to record into as well (or instead, when <see cref="PublishUrl"/> is null).</summary>
    public string? RecordingPath { get; init; }

    /// <summary>Layers overlaid on the base video, bottom to top. Layer i is named <c>scale@cam{i}</c> / <c>overlay@cam{i}</c>.</summary>
    public IReadOnlyList<VideoLayerJobInput> Layers { get; init; } = [];

    /// <summary>Loopback port for the <c>zmq</c> command filter, enabling live layer moves. Null = no live control.</summary>
    public int? CommandPort { get; init; }

    /// <summary>
    /// False starts with the captured picture off the canvas (a scene without the game); it can be
    /// shown live. Ignored for <see cref="BlankCanvasSource"/>, which has no captured picture.
    /// </summary>
    public bool ShowCapture { get; init; } = true;

    /// <summary>Where the base video goes on the canvas.</summary>
    public Linkast.Core.Camera.NormalizedRect BasePlacement { get; init; } = new(0, 0, 1, 1);

    public Linkast.Core.Camera.BaseFit BaseFit { get; init; } = Linkast.Core.Camera.BaseFit.Fit;

    /// <summary>The part of the base video that is shown, as fractions of it (default: all of it).</summary>
    public Linkast.Core.Camera.NormalizedRect BaseCrop { get; init; } = new(0, 0, 1, 1);
}
