# Generates src/Linkast.App/Themes/Tokens.Dark.xaml and Tokens.Light.xaml from colors.txt (name|dark|light)
# and fluent-bridge.txt (Fluent key|dark token|light token). Run from Git Bash:
#   sh tools/theme/gen-tokens.sh Dark src/Linkast.App/Themes/Tokens.Dark.xaml
#   sh tools/theme/gen-tokens.sh Light src/Linkast.App/Themes/Tokens.Light.xaml
X="$(dirname "$0")"; col=$([ "$1" = Dark ] && echo 2 || echo 3)
{
echo '<!-- SPDX-License-Identifier: GPL-3.0-or-later -->'
echo '<ResourceDictionary xmlns="http://schemas.microsoft.com/winfx/2006/xaml/presentation"'
echo '                    xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml"'
echo '                    xmlns:sys="clr-namespace:System;assembly=mscorlib">'
echo "  <!-- Linkast $1 colour tokens, generated by tools/theme/gen-tokens.sh: edit colors.txt there, not this file.
       Tokens.Dark.xaml and Tokens.Light.xaml have identical keys; ThemeService"
echo "       swaps one for the other. Reference these with DynamicResource so a theme change applies live. -->"
echo
while IFS='|' read -r n d l; do v=$([ "$col" = 2 ] && echo "$d" || echo "$l"); printf '  <Color x:Key="Linkast.%sColor">%s</Color>\n' "$n" "$v"; done < "$X/colors.txt"
echo
while IFS='|' read -r n d l; do printf '  <SolidColorBrush x:Key="Linkast.%s" Color="{StaticResource Linkast.%sColor}"/>\n' "$n" "$n"; done < "$X/colors.txt"
cat <<'GRAD'

  <LinearGradientBrush x:Key="Linkast.BrandGradient" StartPoint="0,0" EndPoint="1,1">
    <GradientStop Color="{StaticResource Linkast.BrandCyanColor}" Offset="0"/>
    <GradientStop Color="{StaticResource Linkast.BrandBlueColor}" Offset="0.52"/>
    <GradientStop Color="{StaticResource Linkast.BrandVioletColor}" Offset="1"/>
  </LinearGradientBrush>
  <!-- Go live button: the same three stops, left to right. -->
  <LinearGradientBrush x:Key="Linkast.GoLiveGradient" StartPoint="0,0.3" EndPoint="1,0.7">
    <GradientStop Color="{StaticResource Linkast.BrandCyanColor}" Offset="0"/>
    <GradientStop Color="{StaticResource Linkast.BrandBlueColor}" Offset="0.52"/>
    <GradientStop Color="{StaticResource Linkast.BrandVioletColor}" Offset="1"/>
  </LinearGradientBrush>
  <LinearGradientBrush x:Key="Linkast.NavMarkerGradient" StartPoint="0,0" EndPoint="0,1">
    <GradientStop Color="{StaticResource Linkast.BrandCyanColor}" Offset="0"/>
    <GradientStop Color="{StaticResource Linkast.BrandBlueColor}" Offset="0.5"/>
    <GradientStop Color="{StaticResource Linkast.BrandVioletColor}" Offset="1"/>
  </LinearGradientBrush>

  <!-- Fluent bridge: the stock Fluent controls (ComboBox, CheckBox, Slider, TextBox, ListBox…) read these keys.
       Pointing them at Linkast tokens gives those controls the brand accent and the navy-tinted text colours
       instead of the Windows accent. Fluent's translucent control fills then tint themselves from AppBg. -->
GRAD
while IFS='|' read -r k d l; do t=$([ "$col" = 2 ] && echo "$d" || echo "$l"); printf '  <SolidColorBrush x:Key="%s" Color="{StaticResource Linkast.%sColor}"/>\n' "$k" "$t"; done < "$X/fluent-bridge.txt"
cat <<'SHAPE'

  <!-- Fluent geometry: the stock controls get Linkast corner radii (5 px controls so check boxes stay square,
       8 px drop-down buttons, 10 px pop-ups)
       and the same 34 px height as Linkast buttons. -->
  <CornerRadius x:Key="ControlCornerRadius">5</CornerRadius>
  <CornerRadius x:Key="ComboBoxDropDownButtonBackgroundCornerRadius">8</CornerRadius>
  <CornerRadius x:Key="OverlayCornerRadius">10</CornerRadius>
  <CornerRadius x:Key="PopupCornerRadius">10</CornerRadius>
  <sys:Double x:Key="TextControlThemeMinHeight">34</sys:Double>
SHAPE
echo '</ResourceDictionary>'
} > "$2"
